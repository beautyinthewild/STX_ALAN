

#How to upload your RProjects to GitHub. Found on YouTube. Easy to share!
# Go to this link for instructions: https://www.youtube.com/watch?v=vpRkAoCqX3o

# Type "cmd" in your search panel on your windows laptop. A block box will pop
# up. Copy and paste your working directory file name on the screen. Press Enter. 
# Copy the first 3 lines in your github and press enter. Then copy and paste the  
# last four lines and press enter. Refresh your github page and all your files 
# and folders will appear!